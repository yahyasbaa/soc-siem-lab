#!/usr/bin/env python3
"""Render configuration files that embed secrets from .env.

Outputs (git-ignored) into wazuh/generated/:
  internal_users.yml  - OpenSearch security users with bcrypt hashes
  wazuh.yml           - Wazuh dashboard -> manager API connection
"""
import os
import pathlib
import sys

import bcrypt

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "wazuh" / "generated"


def load_env(path: pathlib.Path) -> dict:
    env = {}
    for line in path.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        env[key.strip()] = value.strip()
    return env


def bhash(password: str) -> str:
    return bcrypt.hashpw(password.encode(), bcrypt.gensalt(rounds=12)).decode()


def main() -> int:
    env_file = ROOT / ".env"
    if not env_file.exists():
        print("render_config: .env not found, run `make setup`", file=sys.stderr)
        return 1
    env = load_env(env_file)
    OUT.mkdir(parents=True, exist_ok=True)

    users = f"""---
# GENERATED by scripts/render_config.py from .env - do not edit by hand.
_meta:
  type: "internalusers"
  config_version: 2

{env['INDEXER_USERNAME']}:
  hash: "{bhash(env['INDEXER_PASSWORD'])}"
  reserved: true
  backend_roles:
  - "admin"
  description: "SOC lab administrator (lab-only credential)"

{env['DASHBOARD_USERNAME']}:
  hash: "{bhash(env['DASHBOARD_PASSWORD'])}"
  reserved: true
  description: "Dashboard server user (lab-only credential)"
"""
    (OUT / "internal_users.yml").write_text(users)

    wazuh_yml = f"""# GENERATED by scripts/render_config.py from .env - do not edit by hand.
hosts:
  - soc-lab:
      url: "https://wazuh.manager"
      port: 55000
      username: {env['API_USERNAME']}
      password: "{env['API_PASSWORD']}"
      run_as: false
"""
    (OUT / "wazuh.yml").write_text(wazuh_yml)
    for f in OUT.iterdir():
        os.chmod(f, 0o644)
    print(f"render_config: wrote {', '.join(sorted(p.name for p in OUT.iterdir()))}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
