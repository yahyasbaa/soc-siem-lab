#!/usr/bin/env python3
"""Generate documentation from the detection catalog, fixtures and test results.

  docs/detection-catalog.md    one row per detection + full detail sections
  docs/mitre-mapping.md        technique -> detections matrix
  docs/telemetry-scenarios.md  every synthetic scenario and its expected result

Measured detection latency is taken from reports/detection-results.json
(written by tests/detection/test_detections_e2e.py) when present.
"""
from __future__ import annotations

import json
import pathlib
import sys
from collections import defaultdict

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts" / "generate-test-events"))
import socgen  # noqa: E402

DOCS = ROOT / "docs"
HEADER = "<!-- GENERATED by scripts/build_docs.py (make docs) - do not edit by hand -->\n\n"


def severity(level: int) -> str:
    return socgen.severity_for_level(level)


def latency_by_rule() -> tuple[dict, str | None]:
    f = ROOT / "reports" / "detection-results.json"
    if not f.exists():
        return {}, None
    data = json.loads(f.read_text())
    out: dict[str, list] = defaultdict(list)
    for r in data["results"]:
        if r["result"] == "pass":
            out[r["rule_id"]].append(r["detection_latency_s"])
    return {k: max(v) for k, v in out.items()}, data.get("run_started")


def md_escape(s: str) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ")


def catalog_md(cat: dict, lat: dict, run: str | None) -> str:
    dets = cat["detections"]
    lines = [HEADER + "# Detection catalog", "",
             f"{len(dets)} detections (+{len(cat['pipeline_rules'])} pipeline-health rules). "
             "Source of truth: `detections/catalog.yml`; rules: `wazuh/manager/etc/rules/soc_lab_rules.xml`.", "",
             "Severity is derived from the Wazuh rule level: **low** 0-6, **medium** 7-11, **high** 12-14, **critical** 15.", "",
             "*Test* lists the positive fixtures (alert must fire) and negative fixtures (benign activity, alert must "
             "**not** fire). Every row is verified end-to-end by `make detection-test`.", ""]
    if run:
        lines += [f"*Detection latency* = time from the synthetic event being written on the lab host to the alert "
                  f"being generated by the manager (worst case across fixtures), measured in the test run started {run}.", ""]
    lines += ["| Rule ID | Detection | Severity | Data source | MITRE technique | Test | Latency (s) | Response |",
              "|---|---|---|---|---|---|---|---|"]
    for d in dets:
        tests = ", ".join(f"`{t}`" for t in d["tests"])
        if d.get("negative_tests"):
            tests += " / FP: " + ", ".join(f"`{t}`" for t in d["negative_tests"])
        lines.append(
            f"| {d['rule_id']} ({d['id']}) | {md_escape(d['name'])} | {severity(d['level'])} ({d['level']}) | "
            f"{md_escape(d['data_source'])} | {', '.join(m['id'] for m in d['mitre'])} | {tests} | "
            f"{lat.get(d['rule_id'], 'n/a')} | {d['playbook']} |")
    lines += ["", "## Pipeline-health rules", "", "| Rule ID | Name | Purpose |", "|---|---|---|"]
    for p in cat["pipeline_rules"]:
        lines.append(f"| {p['rule_id']} | {p['name']} | {md_escape(p['purpose'])} |")
    lines += ["", "## Detection details", ""]
    for d in dets:
        lines += [f"### {d['id']} — {d['name']} (rule {d['rule_id']})", "",
                  f"* **Description:** {d['description']}",
                  f"* **Severity:** {severity(d['level'])} (Wazuh level {d['level']})",
                  f"* **Data source:** {d['data_source']}",
                  f"* **Detection logic:** {d['detection_logic']}",
                  "* **MITRE ATT&CK:** " + "; ".join(f"{m['id']} {m['name']} ({m['tactic']})" for m in d["mitre"]),
                  f"* **False-positive considerations:** {d['false_positives']}",
                  f"* **Recommended response:** {d['response']} → playbook `{d['playbook']}`",
                  f"* **True-positive test:** {', '.join(d['tests'])}",
                  f"* **False-positive test:** {', '.join(d.get('negative_tests') or ['none (no benign variant of this event type)'])}",
                  f"* **Measured detection latency:** {lat.get(d['rule_id'], 'n/a')} s", ""]
    return "\n".join(lines) + "\n"


def mitre_md(cat: dict) -> str:
    by_tech: dict[str, dict] = {}
    for d in cat["detections"]:
        for m in d["mitre"]:
            t = by_tech.setdefault(m["id"], {"name": m["name"], "tactic": m["tactic"], "dets": []})
            t["dets"].append(d)
    lines = [HEADER + "# MITRE ATT&CK mapping", "",
             f"{len(by_tech)} techniques/sub-techniques covered by {len(cat['detections'])} detections. "
             "Wazuh enriches every alert with technique name and tactic from its bundled ATT&CK database "
             "(`rule.mitre.*`); the end-to-end tests assert the ids on every alert.", "",
             "## Coverage by tactic", ""]
    tactics: dict[str, set] = defaultdict(set)
    for tid, t in by_tech.items():
        tactics[t["tactic"]].add(tid)
    order = ["Reconnaissance", "Initial Access", "Execution", "Persistence", "Privilege Escalation",
             "Defense Evasion", "Credential Access", "Discovery", "Command and Control"]
    lines += ["| Tactic | Techniques |", "|---|---|"]
    for tac in order + sorted(set(tactics) - set(order)):
        if tac in tactics:
            lines.append(f"| {tac} | {', '.join(sorted(tactics[tac]))} |")
    lines += ["", "## Detection mapping", "",
              "| Detection | Technique ID | Technique name | Data source | Detection logic | Severity | Recommended response |",
              "|---|---|---|---|---|---|---|"]
    for d in cat["detections"]:
        for m in d["mitre"]:
            lines.append(f"| {d['id']} {md_escape(d['name'])} ({d['rule_id']}) | {m['id']} | {md_escape(m['name'])} | "
                         f"{md_escape(d['data_source'])} | {md_escape(d['detection_logic'])} | "
                         f"{severity(d['level'])} ({d['level']}) | {md_escape(d['response'])} |")
    lines += ["", "## Technique index", "", "| Technique | Name | Tactic | Rules |", "|---|---|---|---|"]
    for tid in sorted(by_tech):
        t = by_tech[tid]
        lines.append(f"| [{tid}](https://attack.mitre.org/techniques/{tid.replace('.', '/')}/) | {md_escape(t['name'])} | "
                     f"{t['tactic']} | {', '.join(d['rule_id'] for d in t['dets'])} |")
    return "\n".join(lines) + "\n"


def scenarios_md() -> str:
    sc = socgen.load_scenarios()
    pos = [s for s in sc if s.kind == "positive"]
    lines = [HEADER + "# Synthetic telemetry scenarios", "",
             f"{len(sc)} deterministic scenarios ({len(pos)} positive, {len(sc) - len(pos)} benign/negative) in "
             "`tests/fixtures/security_events/`. They are **data only**: rendered log lines appended to the files "
             "the lab agents tail. Nothing is executed and no network traffic is sent. All IPs are RFC 5737 "
             "documentation addresses or the private lab range.", "",
             "Render any scenario: `python scripts/generate-test-events/generate.py render <id> --fixed-time 2026-01-01T00:00:00Z`", "",
             "| Scenario | Kind | Lab host | Events | Expected result |", "|---|---|---|---|---|"]
    for s in sc:
        n = sum(int(e.get("repeat", 1)) for e in s.data["events"])
        if s.kind == "positive":
            res = ", ".join(f"{e['rule_id']} (level {e['level']}, {'/'.join(e['mitre'])})" for e in s.expect)
        else:
            res = "must NOT fire: " + ", ".join(s.forbid_rules)
        lines.append(f"| `{s.id}` — {md_escape(s.data['title'])} | {s.kind} | {s.host} | {n} | {res} |")
    lines += ["", "## Scenario descriptions", ""]
    for s in sc:
        lines += [f"* **{s.id}** — {md_escape(s.data['description'])}"]
    return "\n".join(lines) + "\n"


def main() -> int:
    cat = yaml.safe_load((ROOT / "detections" / "catalog.yml").read_text())
    lat, run = latency_by_rule()
    DOCS.mkdir(exist_ok=True)
    (DOCS / "detection-catalog.md").write_text(catalog_md(cat, lat, run))
    (DOCS / "mitre-mapping.md").write_text(mitre_md(cat))
    (DOCS / "telemetry-scenarios.md").write_text(scenarios_md())
    print("wrote docs/detection-catalog.md, docs/mitre-mapping.md, docs/telemetry-scenarios.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
